#!/usr/bin/env python3
"""Wild Wordopia 用の「単語の絵・絵の英文・語派のはなし」サイドカーを作る。

入力（すべて公開済みの生成物。書き換えない）:
  app/eigo-no-e/data.js   … Pictpedia の画像対応（dictionaryIndex ごとの絵とレビュー済みキャプション）
  app/data/branches.csv   … エティモペディアの「語派のはなし」本文
  app/data/ui.csv         … グリムの法則の本文と例（br_grimm_*）

出力:
  app/data/wild-wordopia-pictures.js  （file:// でも読める window.WILDWORDOPIA_PICTURES）

方針:
  - 画像は bindingStatus=bound かつ status!=mismatch のものだけ。
  - キャプション（英文と和訳）は description.status=reviewed のものだけ載せる。
  - 実行時に w（綴り）で dictionaryIndex との対応を再確認する。
  - 語義・語源・画像そのものは作文も変更もしない。app/data/pie/ は読まない。

使い方:  python tools/build_wild_wordopia_pictures.py [--root <checkout>]
"""
import argparse
import csv
import hashlib
import io
import json
import pathlib
import sys


def load_js_object(path, prefix):
    text = path.read_text(encoding="utf-8")
    start = text.index(prefix) + len(prefix)
    start = text.index("{", start)
    obj, _ = json.JSONDecoder().raw_decode(text[start:])
    return obj


def read_csv(path):
    text = path.read_text(encoding="utf-8-sig")
    return list(csv.DictReader(io.StringIO(text)))


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--root", default=str(pathlib.Path(__file__).resolve().parents[1]))
    args = ap.parse_args()
    root = pathlib.Path(args.root)

    eigo = load_js_object(root / "app/eigo-no-e/data.js", "window.EIGO_NO_E")
    pics = {}
    for w in eigo["words"]:
        idx = w.get("dictionaryIndex")
        if not isinstance(idx, int) or w.get("bindingStatus") != "bound" or w.get("status") == "mismatch":
            continue
        image = (w.get("image") or {}).get("path") or ""
        if not image.startswith("assets/word/"):
            continue
        thumb = w.get("thumb") or {}
        tpath = thumb.get("path") or ""
        rec = {
            "w": w.get("w", ""),
            "i": image[len("assets/word/"):],
            "v": (w["image"].get("sha256") or "")[:12],
        }
        if tpath.startswith("eigo-no-e/thumbs/"):
            rec["t"] = tpath[len("eigo-no-e/thumbs/"):]
        d = w.get("description") or {}
        if d.get("status") == "reviewed" and d.get("en"):
            rec["en"] = d["en"]
            if d.get("ja"):
                rec["ja"] = d["ja"]
        if idx in pics:
            print(f"duplicate dictionaryIndex {idx}; keeping first", file=sys.stderr)
            continue
        pics[idx] = rec

    branches = read_csv(root / "app/data/branches.csv")
    ui = {r["key"]: r["value"] for r in read_csv(root / "app/data/ui.csv")}
    grimm = {
        "title": ui.get("br_grimm_t", ""),
        "body": ui.get("br_grimm_b", ""),
        "pairs": [p.split("|") for p in ui.get("br_grimm_pairs", "").split(";") if p],
        "img": ui.get("br_grimm_img", ""),
        "head": ui.get("br_head", ""),
        "sub": ui.get("br_sub", ""),
    }

    payload = {
        "schema": 1,
        "source": {
            "eigoNoEWords": eigo.get("sources", {}).get("words_sha256", ""),
            "pictureCount": len(pics),
        },
        "pictures": {str(k): v for k, v in sorted(pics.items())},
        "branches": branches,
        "grimm": grimm,
    }
    body = json.dumps(payload, ensure_ascii=False, separators=(",", ":"))
    out = root / "app/data/wild-wordopia-pictures.js"
    out.write_text(
        "// Generated by tools/build_wild_wordopia_pictures.py. Do not edit.\n"
        f"// sha256(json)={hashlib.sha256(body.encode()).hexdigest()}\n"
        f"window.WILDWORDOPIA_PICTURES={body};\n",
        encoding="utf-8",
        newline="\n",
    )
    reviewed = sum(1 for v in pics.values() if "en" in v)
    print(f"wrote {out} pictures={len(pics)} captions={reviewed} branches={len(branches)}")


if __name__ == "__main__":
    main()
