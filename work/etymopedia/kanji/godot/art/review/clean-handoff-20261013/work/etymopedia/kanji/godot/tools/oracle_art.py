def main():
    p = os.path.join(ROOT, "data", "jgw.json")
    d = json.load(open(p, encoding="utf-8"))
    for ch, (w, h, lw, strokes) in ART.items():
        d[ch] = {"vb": [0, 0, w, h], "p": [path(s) for s in strokes], "w": lw, "art": True}
    json.dump(d, open(p, "w", encoding="utf-8"), ensure_ascii=False, separators=(",", ":"))
    try:
        from PIL import Image, ImageDraw
        S = 4
        im = Image.new("L", (len(ART) * 130 * S, 160 * S), 255)
        dr = ImageDraw.Draw(im)
        for i, (ch, (w, h, lw, strokes)) in enumerate(ART.items()):
            ox = i * 130 * S + 10 * S
            for s in strokes:
                q = [(ox + x * S, 6 * S + y * S) for x, y in s]
                dr.line(q, fill=0, width=int(lw * 1.7 * S), joint="curve")
                for e in (q[0], q[-1]):
                    r = lw * 1.7 * S / 2
                    dr.ellipse([e[0] - r, e[1] - r, e[0] + r, e[1] + r], fill=0)
        im.resize((im.width // 2, im.height // 2), Image.LANCZOS).save(os.path.join(HERE, "oracle_preview.png"))
    except ImportError:
        pass
    print("描き直した字:", "".join(ART.keys()))

if __name__ == "__main__":
    main()
