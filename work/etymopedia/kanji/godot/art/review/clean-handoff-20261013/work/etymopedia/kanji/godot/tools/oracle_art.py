def cr(pts, n=10):
    """制御点を通る曲線（Catmull-Rom）。'|' を挟むとそこは角にする"""
    segs = [[]]
    for p in pts:
        if p == "|":
            segs.append([segs[-1][-1]])
        else:
            segs[-1].append(p)
    out = []
    for s in segs:
        if len(s) == 2:
            out += [s[0], s[1]] if not out else [s[1]]
            continue
        P = [s[0]] + s + [s[-1]]
        for i in range(1, len(P) - 2):
            p0, p1, p2, p3 = P[i - 1], P[i], P[i + 1], P[i + 2]
            for k in range(n):
                t = k / n
                t2, t3 = t * t, t * t * t
                x = 0.5 * ((2 * p1[0]) + (-p0[0] + p2[0]) * t + (2 * p0[0] - 5 * p1[0] + 4 * p2[0] - p3[0]) * t2 + (-p0[0] + 3 * p1[0] - 3 * p2[0] + p3[0]) * t3)
                y = 0.5 * ((2 * p1[1]) + (-p0[1] + p2[1]) * t + (2 * p0[1] - 5 * p1[1] + 4 * p2[1] - p3[1]) * t2 + (-p0[1] + 3 * p1[1] - 3 * p2[1] + p3[1]) * t3)
                if not out or (abs(out[-1][0] - x) + abs(out[-1][1] - y)) > 0.01:
                    out.append((x, y))
        out.append(s[-1])
    return out

def path(pts):
    return "M " + " L ".join("%.2f %.2f" % p for p in pts)

