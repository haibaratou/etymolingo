const test=require('node:test'),assert=require('node:assert/strict');
const api=require('./multilingual-answers.js');
const w={w:'mountain',p:['men-2'],ja:'山',en:'peak',k:'マウンテン'};
const ja={text:'山',kana:'やま',romanization:'yama',accepted_inputs:['yama'],status:'reviewed'};
const zh={text:'山',pinyin:'shān',accepted_inputs:['shān','shan'],status:'reviewed'};
const make=(a=ja,b=zh)=>api.index({schema:1,entries:[{w:w.w,p:w.p,senses:[{index:0,ja_gloss:'山',en_gloss:'peak',ja:a,zh:b}]}]});
test('renders distinct Japanese and Chinese vocabulary',()=>{assert.match(api.html(make(),w,'ja'),/山 \/ yama/);assert.match(api.html(make(),w,'zh'),/山 \/ shān/);assert.doesNotMatch(api.html(make(),w,'ja'),/マウンテン/)});
test('explicit tone and plain aliases accept; unrelated forms do not',()=>{assert.equal(api.accepts(make(),w,0,'zh','shan'),true);assert.equal(api.accepts(make(),w,0,'zh','shān'),true);assert.equal(api.accepts(make(),w,0,'zh','shàn'),false)});
test('candidates cannot be game answers',()=>assert.equal(api.accepts(make({...ja,status:'candidate'}),w,0,'ja','yama'),false));
test('stale gloss and different homographs are excluded',()=>{assert.equal(api.accepts(make(),{...w,ja:'山脈'},0,'ja','yama'),false);assert.equal(api.accepts(make(),{...w,p:[]},0,'ja','yama'),false)});
test('empty state does not invent answer',()=>assert.match(api.html(new Map(),w,'ja'),/未入力/));
test('rendered answer escaped',()=>assert.match(api.html(make({...ja,text:'<img onerror="x">'}),w,'ja'),/&lt;img/));
