// Reuse reviewed dictionary identities and immutable image packs for direct links.
const fs=require('node:fs'),path=require('node:path'),vm=require('node:vm'),crypto=require('node:crypto');
const root=path.resolve(__dirname,'../../..'),ctx={window:{}};
vm.runInNewContext(fs.readFileSync(path.join(root,'app/eigo-no-e/data.js'),'utf8'),ctx);
const data=ctx.window.EIGO_NO_E;
const {buildSnapshotCatalog}=require('../../eigo-no-e/catalog-validation.js');
const rows=buildSnapshotCatalog(data).words.map(w=>({
 id:w.id,en:w.w,w:/^[ぁ-ゔー]{1,14}$/.test(w.k)?w.k:'',ja:w.ja,pic:w.art,rank:w.r,
 dictionaryRequested:true,dictionarySources:data.sources,updatedArt:false,
 sceneBinding:{w:w.w,p:w.p,ja:w.ja,en:w.en},
 reviewedScene:{schema:1,status:'reviewed',w:w.w,p:w.p,art:w.art,sense:w.sense,scene:w.scene,image:w.image},
 sceneAsset:`picture-words/scene-assets/${w.art}@${w.image.sha256}.js`
}));
let added=0;
for(const w of rows){
 const bytes=fs.readFileSync(path.join(root,w.reviewedScene.image.path));
 const sha=crypto.createHash('sha256').update(bytes).digest('hex');
 if(sha!==w.reviewedScene.image.sha256)throw Error('Changed image: '+w.id);
 const dest=path.join(root,'app/games',w.sceneAsset);
 if(!fs.existsSync(dest)){fs.writeFileSync(dest,`(window.PICTURE_WORDS_SCENE_ASSETS ||= {})[${JSON.stringify(sha)}] = ${JSON.stringify({mime:'image/png',base64:bytes.toString('base64')})};\n`);added++;}
}
fs.writeFileSync(path.join(__dirname,'dictionary-links.js'),'// Generated by build-dictionary-links.cjs; loaded only for a requested word.\nwindow.PICTURE_WORDS_DICTIONARY_LINKS = '+JSON.stringify(rows)+';\n');
console.log(`${rows.length} exact dictionary entries; ${added} new immutable image packs`);
