"""Derive file://-readable scripts from the public Japanese JSON, without editing it.

Run from any directory. --check is read-only; --output permits an isolated build.
All writes replace temporary files, so existing NTFS hardlinks are never overwritten.
"""
from pathlib import Path
import argparse
import hashlib
import json
import os
import tempfile


def atomic_write(path, content):
    path.parent.mkdir(parents=True, exist_ok=True)
    if path.exists() and path.read_bytes() == content:
        return
    fd, temporary = tempfile.mkstemp(prefix=path.name + '.', suffix='.tmp', dir=path.parent)
    try:
        with os.fdopen(fd, 'wb') as stream:
            stream.write(content)
        os.replace(temporary, path)
    finally:
        if os.path.exists(temporary):
            os.unlink(temporary)


def js_string(value):
    # A JSON string, never an executable object literal or an HTML interpolation.
    return (json.dumps(value, ensure_ascii=False, separators=(',', ':'))
            .replace('<', '\\u003c').replace('\u2028', '\\u2028').replace('\u2029', '\\u2029'))


def build(data_dir, output_dir, check=False):
    data_dir, output_dir = Path(data_dir), Path(output_dir)
    inputs = [('index', data_dir / 'ja_index.json')]
    inputs += [(p.stem, p) for p in sorted((data_dir / 'ja_det').glob('*.json'))]
    if len(inputs) == 1:
        raise ValueError('No Japanese dictionary detail shards found')
    manifest = {'schema': 1, 'index': None, 'shards': {}}
    outputs = {}
    source_bytes = 0
    for key, path in inputs:
        raw = path.read_bytes()
        text = raw.decode('utf-8-sig')
        value = json.loads(text)
        if not isinstance(value, list if key == 'index' else dict):
            raise ValueError('Unexpected JSON structure: ' + str(path))
        digest = hashlib.sha256(raw).hexdigest()
        label = 'index' if key == 'index' else 'det-' + '-'.join(format(ord(c), 'x') for c in key)
        filename = label + '-' + digest + '.js'
        # JSON.parse preserves every original value, including own __proto__ keys.
        script = ('// Generated by app/support/ja-dict/build_local_data.py; do not edit.\n'
                  'globalThis.JaDictData.register(' + js_string(key) + ',' + js_string(digest)
                  + ',JSON.parse(' + js_string(text) + '));\n').encode('utf-8')
        outputs[filename] = script
        entry = {'file': filename, 'sha256': digest, 'records': len(value)}
        if key == 'index':
            manifest['index'] = entry
        else:
            manifest['shards'][key] = entry
        source_bytes += len(raw)
    outputs['manifest.js'] = ('// Generated; contains only public ja_index / ja_det metadata.\n'
                              'globalThis.JaDictData.registerManifest(JSON.parse('
                              + js_string(json.dumps(manifest, ensure_ascii=False, separators=(',', ':')))
                              + '));\n').encode('utf-8')
    # Prepare everything before writing, and activate the manifest last. Previous
    # content-addressed files remain available to tabs holding an older manifest.
    for name, content in outputs.items():
        target = output_dir / name
        if check:
            if not target.is_file() or target.read_bytes() != content:
                raise ValueError('Local dictionary data is missing or stale: ' + str(target))
        else:
            atomic_write(target, content)
    return {'indexRecords': manifest['index']['records'], 'detailShards': len(manifest['shards']),
            'detailRecords': sum(v['records'] for v in manifest['shards'].values()),
            'sourceBytes': source_bytes, 'scriptBytes': sum(map(len, outputs.values())),
            'indexSha256': manifest['index']['sha256'], 'files': len(outputs)}


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--data', type=Path, default=Path(__file__).resolve().parents[2] / 'data/ja')
    parser.add_argument('--output', type=Path)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    result = build(args.data, args.output or args.data / 'file', check=args.check)
    print(json.dumps(result, ensure_ascii=False))
