/* Limited file:// view projection. Public dictionary inputs and artwork are read-only. */
'use strict';
const fs=require('node:fs'),path=require('node:path'),crypto=require('node:crypto'),zlib=require('node:zlib');
const {key}=require('./learning-levels.js');
const root=path.resolve(__dirname,'../../..'),check=process.argv.includes('--check');
const hash=raw=>crypto.createHash('sha256').update(raw).digest('hex');
function csv(text){
 const rows=[];let row=[],cur='',q=false;text=text.replace(/^\uFEFF/,'');
 for(let i=0;i<text.length;i++){const c=text[i];if(q){if(c==='"'){if(text[i+1]==='"'){cur+='"';i++;}else q=false;}else cur+=c;}else if(c==='"')q=true;else if(c===','){row.push(cur);cur='';}else if(c==='\n'||c==='\r'){if(c==='\r'&&text[i+1]==='\n')i++;row.push(cur);if(row.length>1||row[0])rows.push(row);row=[];cur='';}else cur+=c;}
 if(cur||row.length){row.push(cur);rows.push(row);}
 const head=rows.shift();return rows.filter(r=>r.length>1).map(r=>Object.fromEntries(head.map((h,i)=>[h,r[i]||''])));
}
function main(){
 const inputs=new Map();
 const read=p=>{const raw=fs.readFileSync(path.join(root,p));inputs.set(p,raw);return raw;};
 const wordBytes=read('app/data/generated-etymon/words.json'),rootBytes=read('app/data/generated-etymon/roots.json');
 const words=JSON.parse(wordBytes),roots=JSON.parse(rootBytes);
 const htmlPath=path.join(root,'app/etymopedia.html'),html=fs.readFileSync(htmlPath,'utf8');
 const embedded=JSON.parse(html.match(/^const EMB_CSV = (\{.*\});\s*\/\*/m)?.[1]||'{}');
 const layouts={};for(const name of ['words.csv','lexicon.csv','roots.csv'])layouts[name]=[read('app/data/'+name).toString('utf8'),embedded[name]||''];
 const wanted=new Set(),rootKeys=new Set();
 for(const name of ['words.csv','lexicon.csv'])for(const raw of layouts[name])for(const row of csv(raw))wanted.add(key({w:row.w,p:(row.p||'').split('+').filter(Boolean)}));
 for(const raw of layouts['roots.csv'])for(const row of csv(raw))rootKeys.add(row.pie);
 const dets=new Map(),selected=[];
 words.forEach((word,i)=>{
  if(!wanted.has(key(word)))return;
  const row=Object.fromEntries(['w','p','ja','en','pos','g','r','b'].map(k=>[k,word[k]??(k==='p'?[]:'')]));
  const letter=/^[a-z]/i.test(word.w)?word.w[0].toLowerCase():'_';
  if(!dets.has(letter)){const p='app/data/generated-etymon/det/'+letter+'.json';dets.set(letter,JSON.parse(read(p)));}
  const record=dets.get(letter)[String(i)];row.phonetic=Array.isArray(record)&&record[3]===word.w?String(record[4]||''):'';
  selected.push(row);
 });
 const data={schema:1,source:'app/data/generated-etymon/',wordsSha256:hash(wordBytes),rootsSha256:hash(rootBytes),canonicalWordCount:words.length,layoutSha256:Object.fromEntries(Object.entries(layouts).map(([name,values])=>[name,values.map(hash)])),words:selected,roots:roots.filter(r=>rootKeys.has(r.key)).map(r=>Object.fromEntries(['key','ja','d','definition_reviewed','definition_source'].map(k=>[k,r[k]??''])))};
 const raw=Buffer.from(JSON.stringify(data)),envelope={schema:1,encoding:'gzip-base64',sha256:hash(raw),data:zlib.gzipSync(raw,{level:9}).toString('base64')};
 const script='/* Generated by support/etymopedia/build-data.cjs; do not edit. No artwork or saved selections. */\nglobalThis.ETYMOPEDIA_CURRENT_DATA='+JSON.stringify(envelope)+';\n';
 for(const [p,bytes] of inputs)if(!bytes.equals(fs.readFileSync(path.join(root,p))))throw Error('Input changed during build: '+p);
 const target=path.join(__dirname,'current-data.js');
 let updatedHTML=html;
 for(const file of ['data/generated-etymon/weblio-learning-levels.js','data/generated-etymon/learning-levels.js','shared/explorer-difficulty-v2.js','support/etymopedia/learning-levels.js','support/etymopedia/learning-levels.css','support/etymopedia/current-data.js']){
  const content=file.endsWith('/current-data.js')?script:fs.readFileSync(path.join(root,'app',file));
  // This consumer uses only the shared pure API. Vocabulary UI styling can be
  // edited independently without invalidating this page's API-only reference.
  const versioned=file==='shared/explorer-difficulty-v2.js'?content.toString().split('function makeModal(')[0]:content;
  const digest=hash(versioned).slice(0,12);
  const escaped=file.replace(/[.*+?^${}()|[\]\\]/g,'\\$&'),pattern=new RegExp('((?:src|href)=")'+escaped+'(?:\\?[^"\\s]*)?(?=")','g');
  if(!pattern.test(updatedHTML))throw Error('Missing Etymopedia dependency: '+file);
  updatedHTML=updatedHTML.replace(pattern,'$1'+file+'?v='+digest);
 }
 if(check){
  if(!fs.existsSync(target)||fs.readFileSync(target,'utf8')!==script||updatedHTML!==html)throw Error('Etymopedia file data/references are stale; run node app/support/etymopedia/build-data.cjs');
 }else{
  if(fs.readFileSync(htmlPath,'utf8')!==html)throw Error('Etymopedia entry changed during build');
  const temp=target+'.tmp';fs.writeFileSync(temp,script);fs.renameSync(temp,target);
  if(updatedHTML!==html){const tempHTML=htmlPath+'.etymopedia-tmp';fs.writeFileSync(tempHTML,updatedHTML);fs.renameSync(tempHTML,htmlPath);}
 }
 console.log(JSON.stringify({check,canonicalWordCount:words.length,projectedWords:selected.length,roots:data.roots.length,wordsSha256:data.wordsSha256,bytes:Buffer.byteLength(script)}));
}
if(require.main===module)main();
module.exports={csv,main};
